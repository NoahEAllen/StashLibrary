#Requires -Version 5.1
<#
.SYNOPSIS
  导出精选清单：默认只写 Base64（可提交）；加 -Decode 则打印到控制台（勿重定向进仓库）。
  解析 PrimaryB64 + AlternateB64（兼容旧 SelectedB64）。
#>
param(
  [switch]$Decode,
  [string]$OutFile = ""
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
$InstallScript = Join-Path $PSScriptRoot "install-providers.ps1"
if (-not (Test-Path $InstallScript)) { throw "找不到 install-providers.ps1" }

function Decode-B64([string]$b64) {
  return [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($b64))
}

function Extract-Array([string]$raw, [string]$varName) {
  $pat = '\$' + $varName + '\s*=\s*@\((.*?)\)\s*\r?\n'
  $m = [regex]::Match($raw, $pat, [Text.RegularExpressions.RegexOptions]::Singleline)
  if (-not $m.Success) { return @() }
  $block = $m.Groups[1].Value
  return @([regex]::Matches($block, '"([A-Za-z0-9+/=]+)"') | ForEach-Object { $_.Groups[1].Value })
}

$raw = Get-Content $InstallScript -Raw
$primary = Extract-Array $raw 'PrimaryB64'
$alternate = Extract-Array $raw 'AlternateB64'
$legacy = Extract-Array $raw 'SelectedB64'

$tokens = @()
$groups = @()
if ($primary.Count -gt 0 -or $alternate.Count -gt 0) {
  foreach ($t in $primary) { $tokens += $t; $groups += 'primary' }
  foreach ($t in $alternate) { $tokens += $t; $groups += 'alternate' }
} elseif ($legacy.Count -gt 0) {
  foreach ($t in $legacy) { $tokens += $t; $groups += 'all' }
} else {
  throw "无法解析 PrimaryB64 / AlternateB64 / SelectedB64"
}

$list = @()
for ($i = 0; $i -lt $tokens.Count; $i++) {
  $tok = $tokens[$i]
  try {
    $dec = Decode-B64 $tok
    $list += [pscustomobject]@{ B64 = $tok; Name = $dec; Group = $groups[$i] }
  } catch {
    Write-Host "WARN bad b64 token skipped" -ForegroundColor Yellow
  }
}

if (-not $OutFile) {
  $OutFile = Join-Path $Root "presets\provider-list.b64.txt"
}

$header = @(
  "# MediaVault selected providers — Base64 package names",
  "# Generated by export-provider-list.ps1 — safe to commit",
  "# Groups: primary + alternate",
  "# Count: $($list.Count)",
  ""
)
$body = @()
$body += "# --- primary ---"
$body += @($list | Where-Object { $_.Group -eq 'primary' } | ForEach-Object { $_.B64 })
$body += ""
$body += "# --- alternate ---"
$body += @($list | Where-Object { $_.Group -eq 'alternate' } | ForEach-Object { $_.B64 })
$body += @($list | Where-Object { $_.Group -eq 'all' } | ForEach-Object { $_.B64 })

($header + $body) | Set-Content -Path $OutFile -Encoding UTF8
Write-Host "Wrote $($list.Count) entries → $OutFile" -ForegroundColor Green

if ($Decode) {
  Write-Host ""
  Write-Host "Decoded names (console only — do not commit):" -ForegroundColor Yellow
  $list | ForEach-Object { Write-Host ("  [{0}] {1}" -f $_.Group, $_.Name) }
}

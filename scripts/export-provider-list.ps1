#Requires -Version 5.1
<#
.SYNOPSIS
  导出精选清单：默认只写 Base64（可提交）；加 -Decode 则打印到控制台（勿重定向进仓库）。
#>
param(
  [switch]$Decode,
  [string]$OutFile = ""
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
$InstallScript = Join-Path $PSScriptRoot "install-providers.ps1"
if (-not (Test-Path $InstallScript)) { throw "找不到 install-providers.ps1" }

function Decode-B64([string]$b64) {
  return [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($b64))
}

$raw = Get-Content $InstallScript -Raw
# Slice the SelectedB64 = @( ... ) block
$m = [regex]::Match($raw, '\$SelectedB64\s*=\s*@\((.*?)\)\s*\r?\n', [Text.RegularExpressions.RegexOptions]::Singleline)
if (-not $m.Success) { throw "无法解析 SelectedB64 数组" }
$block = $m.Groups[1].Value
$tokens = [regex]::Matches($block, '"([A-Za-z0-9+/=]+)"') | ForEach-Object { $_.Groups[1].Value }

$list = @()
foreach ($tok in $tokens) {
  try {
    $dec = Decode-B64 $tok
    $list += [pscustomobject]@{ B64 = $tok; Name = $dec }
  } catch {
    Write-Host "WARN bad b64 token skipped" -ForegroundColor Yellow
  }
}

if (-not $OutFile) {
  $OutFile = Join-Path $Root "presets\provider-list.b64.txt"
}

$header = @(
  "# MediaVault selected providers — Base64 package names",
  "# Generated by export-provider-list.ps1 — safe to commit",
  "# Count: $($list.Count)",
  ""
)
$body = $list | ForEach-Object { $_.B64 }
($header + $body) | Set-Content -Path $OutFile -Encoding UTF8
Write-Host "Wrote $($list.Count) entries → $OutFile" -ForegroundColor Green

if ($Decode) {
  Write-Host ""
  Write-Host "Decoded names (console only — do not commit):" -ForegroundColor Yellow
  $list | ForEach-Object { Write-Host ("  " + $_.Name) }
}
